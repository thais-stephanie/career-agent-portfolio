def _norm_ws(s: str) -> str:
    return re.sub(r"\s+", " ", s.strip().lower())


@lru_cache(maxsize=1)
def alias_index() -> dict[str, str]:
    """alias (lowercase) -> canonical term."""
    idx: dict[str, str] = {}
    for canon, aliases in ALIASES.items():
        idx[_norm_ws(canon)] = canon
        for a in aliases:
            idx[_norm_ws(a)] = canon
    return idx


def canonical(term: str) -> str:
    """Map a term (any spelling) to its canonical lexicon form, or its normalized self."""
    t = _norm_ws(term)
    return alias_index().get(t, t)


def known_term(text: str) -> bool:
    """True when the whole text is a lexicon term or alias (not merely contains one)."""
    return _norm_ws(text) in alias_index()


@lru_cache(maxsize=1)
def term_pattern() -> re.Pattern[str]:
    """Compiled alternation of every alias, longest first (public for the validator's binding coverage)."""
    terms = sorted(alias_index().keys(), key=len, reverse=True)
    parts = []
    for t in terms:
        esc = re.escape(t)
        # word boundaries that also cope with terms like "c#", "node.js", "ci/cd"
        parts.append(rf"(?<![A-Za-z0-9#+]){esc}(?![A-Za-z0-9#+])")
    return re.compile("|".join(parts), re.IGNORECASE)


def find_terms(text: str) -> list[str]:
    """Canonical lexicon terms found in ``text`` (deduplicated, in order of appearance)."""
    found: list[str] = []
    seen: set[str] = set()
    for m in term_pattern().finditer(text):
        c = alias_index().get(_norm_ws(m.group(0)))
        if c and c not in seen:
            seen.add(c)
            found.append(c)
    return found


