# A general capability the JD names is evidenced by hands-on work with any product that delivers it:
# Power BI or Google Analytics work supports "analytics", Marketo work supports "marketing automation".
# The relation is one-way. Evidence of the capability, or of a sibling product, never makes a *named*
# product more than TRANSFERABLE (Google Analytics is not Adobe Analytics; Power BI is not CJA), and
# a platform category that is a technology in its own right (CDP, CRM) is not a capability here.
CAPABILITY_PRODUCTS: dict[str, frozenset[str]] = {
    "analytics": frozenset(
        t for t in [*CONCEPT_GROUPS["product_analytics"], *CONCEPT_GROUPS["bi"]] if t != "bi"
    ),
    "marketing automation": frozenset(CONCEPT_GROUPS["marketing_automation"]),
}


def capability_products(term: str) -> frozenset[str]:
    """Products whose hands-on use evidences the general capability ``term`` (empty for anything else)."""
    return CAPABILITY_PRODUCTS.get(canonical(term), frozenset())


def evidenced_terms(bank_terms: set[str]) -> set[str]:
    """The bank's own terms plus every general capability one of its evidenced products delivers.
    Nothing flows the other way: a named product is evidenced only by itself."""
    return set(bank_terms) | {
        cap for cap, products in CAPABILITY_PRODUCTS.items() if products & bank_terms
    }


@lru_cache(maxsize=1)
def capability_terms() -> frozenset[str]:
    out = set(_EXTRA_CAPABILITIES)
    for g in CAPABILITY_GROUPS:
        out.update(CONCEPT_GROUPS.get(g, []))
    return frozenset(out)


def term_kind(term: str) -> str:
    """'domain' | 'capability' | 'technology' for a canonical lexicon term."""
    c = canonical(term)
    if c in DOMAIN_TERMS:
        return "domain"
    if c in capability_terms():
        return "capability"
    return "technology"


def group_of(term: str) -> list[str]:
    c = canonical(term)
    return [g for g, members in CONCEPT_GROUPS.items() if c in members]


def has_admin_cue(text: str) -> bool:
    t = text.lower()
    return any(cue in t for cue in ADMIN_CUES)


